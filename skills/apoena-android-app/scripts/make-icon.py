#!/usr/bin/env python3
"""Generate an App's launcher icon and Store icon from a Tabler outline icon.

Usage: make-icon.py --icon book --color E53935 [--project DIR]

Writes, under DIR (default: current directory):
  app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml     adaptive icon (with themed monochrome layer)
  app/src/main/res/drawable/ic_launcher_foreground.xml   the Tabler glyph, white, in the 66dp safe zone
  app/src/main/res/values/ic_launcher_background.xml     the background colour
  fastlane/metadata/android/en-US/images/icon.png        512x512 PNG the Store lists the App with

The Store needs the PNG because fdroidserver cannot draw an adaptive icon. Rendering it needs
rsvg-convert (brew install librsvg) or ImageMagick's magick.
"""
import argparse
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

TABLER_VERSION = "3.49.0"
TABLER_URL = f"https://cdn.jsdelivr.net/npm/@tabler/icons@{TABLER_VERSION}/icons/outline/{{name}}.svg"
SVG_NS = "{http://www.w3.org/2000/svg}"
# The 24-unit glyph scaled 2.5x and centred spans 24..84 of the 108dp canvas: inside the 66dp safe zone.
SCALE, OFFSET = 2.5, 24
STORE_ICON_SIZE = 512
# AA contrast for graphical objects (WCAG 1.4.11).
MIN_CONTRAST = 3.0

FOREGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!-- Tabler Icons "{name}" {version} (MIT, tabler.io), generated by make-icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{scale}"
        android:scaleY="{scale}"
        android:translateX="{offset}"
        android:translateY="{offset}">
        <path
            android:pathData="{path}"
            android:strokeColor="#FFFFFF"
            android:strokeWidth="2"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
    </group>
</vector>
"""

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""

BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#{color}</color>
</resources>
"""

# The launcher shows the middle 72dp of the 108dp canvas; the Store icon is that same square.
STORE_SVG = """<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="72" height="72">
  <rect x="18" y="18" width="72" height="72" fill="#{color}"/>
  <g transform="translate({offset} {offset}) scale({scale})">
    <path d="{path}" fill="none" stroke="#FFFFFF" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>
  </g>
</svg>
"""


def fetch_glyph(name):
    try:
        with urllib.request.urlopen(TABLER_URL.format(name=name), timeout=30) as response:
            svg = ET.fromstring(response.read())
    except urllib.error.HTTPError as e:
        if e.code == 404:
            sys.exit(f"no Tabler outline icon named {name!r} in {TABLER_VERSION} (browse https://tabler.io/icons)")
        raise
    paths = []
    for element in svg:
        if element.tag != f"{SVG_NS}path":
            sys.exit(f"{name}: <{element.tag.removeprefix(SVG_NS)}> is not supported, only <path>")
        if element.get("stroke") == "none":  # Tabler's invisible 24x24 bounding box
            continue
        paths.append(element.get("d"))
    return "".join(paths)


def luminance(hex_color):
    def channel(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (int(hex_color[i:i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def render_png(svg, out):
    with tempfile.NamedTemporaryFile("w", suffix=".svg") as f:
        f.write(svg)
        f.flush()
        size = str(STORE_ICON_SIZE)
        if shutil.which("rsvg-convert"):
            cmd = ["rsvg-convert", "-w", size, "-h", size, f.name, "-o", str(out)]
        elif shutil.which("magick"):
            cmd = ["magick", "-background", "none", "-density", "600", f.name, "-resize", f"{size}x{size}", str(out)]
        else:
            sys.exit("rendering the Store icon needs rsvg-convert (brew install librsvg) or magick")
        subprocess.run(cmd, check=True)


def main():
    parser = argparse.ArgumentParser(description="Generate an App's launcher icon and Store icon.")
    parser.add_argument("--icon", required=True, help="Tabler outline icon name, e.g. book")
    parser.add_argument("--color", required=True, help="background colour as RRGGBB, e.g. E53935")
    parser.add_argument("--project", type=Path, default=Path("."), help="Android project root")
    args = parser.parse_args()

    color = args.color.removeprefix("#").upper()
    if not re.fullmatch(r"[0-9A-F]{6}", color):
        sys.exit(f"--color must be RRGGBB, got {args.color!r}")
    contrast = 1.05 / (luminance(color) + 0.05)
    if contrast < MIN_CONTRAST:
        sys.exit(f"white on #{color} has contrast {contrast:.2f}:1, below {MIN_CONTRAST}:1; pick a darker colour")

    project = args.project
    if not (project / "app/src/main/AndroidManifest.xml").is_file():
        sys.exit(f"{project} has no app/src/main/AndroidManifest.xml")
    path = fetch_glyph(args.icon)
    res = project / "app/src/main/res"
    fmt = {"name": args.icon, "version": TABLER_VERSION, "scale": SCALE, "offset": OFFSET, "path": path, "color": color}

    files = {
        res / "drawable/ic_launcher_foreground.xml": FOREGROUND.format(**fmt),
        res / "mipmap-anydpi-v26/ic_launcher.xml": ADAPTIVE,
        res / "values/ic_launcher_background.xml": BACKGROUND.format(**fmt),
    }
    for file, content in files.items():
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(content)
        print(f"wrote {file}")

    store_icon = project / "fastlane/metadata/android/en-US/images/icon.png"
    store_icon.parent.mkdir(parents=True, exist_ok=True)
    render_png(STORE_SVG.format(**fmt), store_icon)
    print(f"wrote {store_icon}")

    # PNG mipmaps never reach a minSdk 26 release APK: the adaptive icon outranks them.
    stale = sorted(res.glob("mipmap-*dpi/ic_launcher*.png")) + sorted(res.glob("mipmap-*dpi/ic_launcher*.webp"))
    for file in stale:
        print(f"warning: {file} is dead weight next to the adaptive icon; delete it")
    manifest = (project / "app/src/main/AndroidManifest.xml").read_text()
    if 'android:icon="@mipmap/ic_launcher"' not in manifest:
        print('warning: add android:icon="@mipmap/ic_launcher" to <application> in AndroidManifest.xml')


if __name__ == "__main__":
    main()
